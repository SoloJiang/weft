// Generate the macOS-readable mirrors of the Automation (Apple Events) usage
// description that lives in the i18n catalogs.
//
// `src/i18n/{en,zh}.ts` stay authoritative (CLAUDE.md: user-facing strings go
// only through those two). macOS renders the Automation consent prompt itself,
// from the bundle's `InfoPlist.strings` for the user's language — the webview
// (and its catalogs) never see that dialog, so the copy has to be mirrored
// into files the OS reads: one `InfoPlist.strings` per `.lproj`, shipped as
// bundle resources (see `src-tauri/tauri.macos.conf.json`), plus the
// development-region fallback embedded directly in `src-tauri/Info.plist`
// (which this script does NOT rewrite — the drift test compares it against
// the English catalog instead, so an edit to either side fails loudly).
//
// Run after editing the listed key. `tests/frontend/infoPlistStrings.test.ts`
// fails if any generated file (or Info.plist's fallback) drifts from the
// catalogs, so this cannot go stale unnoticed.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { en } from "../src/i18n/en.ts";
import { zh } from "../src/i18n/zh.ts";

/** The one Info.plist key Weft localizes, and the catalog key holding its
 *  copy. A future second usage-description key (e.g. screen recording)
 *  extends this map rather than growing a parallel pipeline. */
const PLIST_KEYS = {
  NSAppleEventsUsageDescription: "settings.computerUseMacosAutomationPrompt",
};

/** Catalog -> the `.lproj` directory macOS reads that language's
 *  `InfoPlist.strings` from. `zh-Hans` (not bare `zh`): the catalogs are
 *  written in Simplified Chinese, and macOS matches the user's language to
 *  the closest available `.lproj` by BCP 47 rules. */
const LOCALES = [
  { catalog: en, lproj: "en.lproj" },
  { catalog: zh, lproj: "zh-Hans.lproj" },
];

function lookup(catalog, key) {
  return key.split(".").reduce((node, part) => node?.[part], catalog);
}

/** `.strings` string-literal escaping: backslash and double-quote, plus
 *  newline for completeness — the catalogs' own copy is single-line. */
function escapeStringsLiteral(value) {
  return value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("\n", "\\n");
}

export function buildInfoPlistStrings(catalog) {
  const lines = [
    "/* Generated by scripts/gen-infoplist-strings.mjs from src/i18n — do not edit by hand. */",
  ];
  for (const [plistKey, catalogKey] of Object.entries(PLIST_KEYS)) {
    const copy = lookup(catalog, catalogKey);
    if (typeof copy !== "string" || copy.length === 0) {
      throw new Error(`${plistKey}: ${catalogKey} is missing from a catalog`);
    }
    lines.push(`"${plistKey}" = "${escapeStringsLiteral(copy)}";`);
  }
  return `${lines.join("\n")}\n`;
}

export function targets() {
  return LOCALES.map(({ catalog, lproj }) => ({
    lproj,
    relPath: `../src-tauri/locales/${lproj}/InfoPlist.strings`,
    content: buildInfoPlistStrings(catalog),
  }));
}

/** The English fallback `src-tauri/Info.plist` must embed verbatim (checked,
 *  not written, by this pipeline — see the header comment). */
export function developmentRegionFallback() {
  return lookup(en, PLIST_KEYS.NSAppleEventsUsageDescription);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const { relPath, content } of targets()) {
    const out = fileURLToPath(new URL(relPath, import.meta.url));
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, content);
    console.log(`wrote ${out}`);
  }
}
